type PlannedEconomyEntry = Omit<
	MigrationEntry,
	"targetDomain" | "requiredTests" | "parityEvidence" | "status" | "notes"
> & {
	requiredTests?: MigrationEntry["requiredTests"];
	notes?: MigrationEntry["notes"];
};

function plannedEconomyEntry(entry: PlannedEconomyEntry): MigrationEntry {
	return {
		...entry,
		targetDomain: "economy",
		requiredTests: entry.requiredTests ?? ["integration", "e2e", "visual"],
		parityEvidence: [],
		status: "PLANNED",
		notes: entry.notes ?? [],
	};
}

