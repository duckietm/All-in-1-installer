import type { MigrationEntry } from "./types";

type PlannedSystemEntry = Omit<
	MigrationEntry,
	"targetDomain" | "requiredTests" | "parityEvidence" | "status" | "notes"
> & {
	requiredTests?: MigrationEntry["requiredTests"];
	notes?: MigrationEntry["notes"];
};

function plannedSystemEntry(entry: PlannedSystemEntry): MigrationEntry {
	return {
		...entry,
		targetDomain: "system",
		requiredTests: entry.requiredTests ?? ["integration", "e2e", "visual"],
		parityEvidence: [],
		status: "PLANNED",
		notes: entry.notes ?? [],
	};
}

