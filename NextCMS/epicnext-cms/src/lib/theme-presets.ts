const DARK_FIRST = new Set(["Midnight", "Galaxy", "Cyberpunk", "Neon", "Dusk"]);

function brandValues(source: Partial<ThemePalette>): Partial<ThemePalette> {
	return {
		color_primary: source.color_primary,
		color_accent: source.color_accent,
		color_success: source.color_success,
		color_warning: source.color_warning,
		color_error: source.color_error,
		color_info: source.color_info,
		button_primary_color: source.button_primary_color ?? source.color_primary,
		border_color: source.border_color ?? source.color_primary,
		panel_border_color:
			source.panel_border_color ?? source.border_color ?? source.color_primary,
		gradient_from: source.color_primary,
		gradient_to: source.color_accent,
		button_outline_color: source.border_color ?? source.color_primary,
	};
}

function completePalette(
	base: ThemePalette,
	values: Partial<ThemePalette>,
): ThemePalette {
	const merged = { ...base, ...values };
	merged.button_secondary_color =
		values.button_secondary_color ?? merged.color_accent;
	merged.button_outline_color =
		values.button_outline_color ?? merged.border_color;
	merged.panel_border_color = values.panel_border_color ?? merged.border_color;
	merged.gradient_from = values.gradient_from ?? merged.color_primary;
	merged.gradient_to = values.gradient_to ?? merged.color_accent;
	return merged;
}

export const PRESETS: Record<string, ThemePreset> = Object.fromEntries(
	Object.entries(LEGACY_PALETTES).map(([name, palette]) => {
		const light = DARK_FIRST.has(name)
			? completePalette(LIGHT_BASE, brandValues(palette))
			: completePalette(LIGHT_BASE, palette);
		const dark = DARK_FIRST.has(name)
			? completePalette(DARK_BASE, palette)
			: completePalette(DARK_BASE, brandValues(palette));
		return [name, { light, dark } satisfies ThemePreset];
	}),
);
